-- =====================================================================
-- PGW Support Portal — migration 68: the Home Office (#1515)
-- =====================================================================
-- Asked for by the user 2026-09-25: "a 'home office' store ... does not
-- produce revenue but handles everything on the back end."
--
-- DECISIONS (user, 2026-09-25):
--   * It holds corporate staff, runs Payroll and the Employee Schedule,
--     and can have its own logins (role 'store' pointed at it).
--   * Store number 1515 — ADP's "Corporate #1515" department, so a later
--     census load lines up by number.
--   * OUTSIDE every district. can_access_location() therefore lets only
--     admin/master (and logins assigned to it) see it; district and
--     regional managers never do. No change to that function.
--   * A new 'Office' position, valid ONLY at the Home Office.
--   * EXCLUDED from company payroll % and every other revenue rollup.
--     Its payroll appears on its own Payroll page and nowhere else.
--   * NOT in the Company Directory (not chosen).
--
-- WHY A NEW FLAG AND NOT is_sandbox. is_sandbox hides a location from
-- store/district/regional users and marks it as fake data; the Home
-- Office is real and must be reachable by its own logins. Migration 38
-- also says sandbox must never be overloaded with a second meaning.
--
-- WHY brand STAYS 'midas'. brand is NOT NULL with a two-value check
-- repeated on four tables. The Home Office uses the Midas payroll
-- engine (hours, hourly/OT, salary, bonus) — the tech/sales columns are
-- hidden by the frontend — so a third brand value would buy nothing but
-- a wider blast radius. is_home_office, not brand, is what every
-- decision below keys off.
--
-- SALARIED OFFICE STAFF. Salary keys off employees.is_store_manager
-- (migration 32), which was limited to ONE position='manager' row per
-- location. Office staff are often salaried, so the check now also
-- allows position 'office', and the one-per-location index is narrowed
-- to managers. Pay math (SQL + lib/payrollMath.js) is unchanged. The
-- column name is historical; the UI labels it "Salaried" for office rows.
--
-- ROLLUPS. Every company scope site already reads
--   where public.can_access_location(l.id) and l.is_sandbox = false
-- and now reads
--   ... and l.is_sandbox = false and not l.is_home_office
-- The eight functions below are the SHIPPED bodies with only that
-- predicate spliced in (generated by build68.mjs, one asserted match
-- count per function). Single-store readers (payroll_pct_summary etc.)
-- are untouched: the Home Office's own Payroll page still works.
--
-- Re-runnable.
-- =====================================================================


