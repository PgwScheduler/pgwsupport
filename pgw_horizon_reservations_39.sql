-- PGW Support Portal — Horizon slot reservations, queue-order
-- correction, and upload precondition 3               (Brief 38, rev. 2)
-- Run AFTER pgw_horizon_seed_2320_38a.sql, in the Supabase SQL Editor.
-- Safe to re-run (idempotent throughout).
-- =====================================================================
-- Migration 38 was built from an earlier revision of the brief. The
-- consolidated brief adds a concept 38 does not have at all -- RESERVED
-- SLOTS -- and reverses two decisions 38 shipped. This file closes that
-- gap. It changes no data; the per-store seed lives in 39a.
--
-- WHAT A RESERVATION IS, AND WHY IT IS NOT A TECHNICIAN.
-- Horizon addresses 20 slots per shop and every slot must account for
-- the labor sales written into it. Two categories of labor sales are
-- generated by people who are not technicians on the roster:
--
--   front_staff  every store, exactly one. Front-of-house staff
--                generate labor sales with NO ASSOCIATED LABOR COST.
--                The slot lets Horizon carry that labor sales figure
--                without attributing uncosted hours to a technician.
--
--   gs_techs     SpeeDee only, exactly one. Pooled general service
--                work. GS TECHS DO CARRY LABOR COST.
--
-- That cost asymmetry is the whole reason these are two kinds and not
-- one boolean: one path writes uncosted labor sales, the other writes
-- costed work. Collapsing them writes cost against a slot that has none
-- or drops cost from a slot that has some -- either way a silent wrong
-- number in an external system, which is the failure mode migration 38
-- exists to prevent. A store may hold one of each; the partial unique
-- index enforces one PER KIND, not one per store.
--
-- WHAT ELSE CHANGES, AND WHY EACH IS A REVERSAL AND NOT A TWEAK:
--
--   1. next_horizon_slot() ordered `last_released_at asc nulls first`.
--      It must be `nulls last`. See section 3.
--
--   2. Migration 38 added location_horizon_slots_occupant_key, a
--      one-employee-per-slot unique index. The consolidated brief says
--      explicitly not to add it yet. See section 2.
--
-- NOT IN SCOPE HERE: the 38 shop numbers, the per-store reservations,
-- and the 464-row slot-state import. Those are data, and they are in
-- pgw_horizon_reservations_seed_39a.sql. Run this file first -- 39a
-- calls reserve_horizon_slot(), which does not exist until this file
-- has run.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0. PREFLIGHT
--    Section 2 drops a unique index. Dropping one can never fail on
--    existing data, so there is nothing to guard there. What IS worth
--    reporting is whether any duplicate occupancy already exists, so
--    that a row this migration stops rejecting is a deliberate seed
--    (3831, section 2) rather than something that crept in unnoticed.
--    Reports; does not raise.
-- ---------------------------------------------------------------------
do $$
declare
  v_dupes int;
begin
  select count(*) into v_dupes
  from (
    select location_id, current_technician_id
    from public.location_horizon_slots
    where current_technician_id is not null
    group by location_id, current_technician_id
    having count(*) > 1
  ) d;

  if v_dupes > 0 then
    raise notice
      'PREFLIGHT: % technician(s) already hold more than one Horizon slot at a store. Expected 0 before 39a; 39a seeds exactly one such case (store 3831, Carlos Moran, slots 8 and 12).',
      v_dupes;
  else
    raise notice 'PREFLIGHT: no duplicate slot occupancy. OK.';
  end if;
end
$$;


